_LABELS_BY_LANGUAGE: dict[str, dict[str, str]] = {
    "th": _LABELS_TH,
    "vi": _LABELS_VI,
    "id": _LABELS_ID,
}

# Countries with no entry here (India, Philippines) genuinely use
# English on this app already — not omitted by mistake.
LANGUAGE_BY_COUNTRY: dict[str, str] = {
    "thailand": "th",
    "vietnam": "vi",
    "indonesia": "id",
}


def get_report_language(country: str) -> str:
    return LANGUAGE_BY_COUNTRY.get((country or "").strip().lower(), "en")


def translate_label(label: str, language: str) -> str:
    """Real, static lookup — English label in, translated label out,
    for the 3 languages above. Any label not in the target language's
    dict (including 'en' itself, or a genuinely untranslated one) just
    returns the original English text rather than a blank or an error
    — a missing translation should never break a report."""
    if language == "en":
        return label
    return _LABELS_BY_LANGUAGE.get(language, {}).get(label, label)
